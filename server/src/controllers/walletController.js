// ── MTN MoMo (Collections API) ───────────────────────────────────────────────────
//
// Flow:
//  1. POST /collection/token/  → Bearer token (cached until expires_in)
//  2. POST /collection/v1_0/requesttopay  → 202 Accepted (we supply X-Reference-Id)
//  3. GET  /collection/v1_0/requesttopay/{referenceId}  → poll for SUCCESSFUL/FAILED
//
// Credentials (from MTN Developer Portal or `npx momo-sandbox`):
//   MOMO_SUBSCRIPTION_KEY  → Primary Key from the Collections product
//   MOMO_USER_ID           → API User UUID  (sandbox: generated by momo-sandbox CLI)
//   MOMO_USER_SECRET       → API Key/Secret (sandbox: generated by momo-sandbox CLI)
// ──────────────────────────────────────────────────────────────────────────────

const MOMO_BASE_URL = process.env.MOMO_BASE_URL || 'https://sandbox.momodeveloper.mtn.com';
const MOMO_SUBSCRIPTION_KEY = process.env.MOMO_SUBSCRIPTION_KEY || '';
const MOMO_USER_ID = process.env.MOMO_USER_ID || '';
const MOMO_USER_SECRET = process.env.MOMO_USER_SECRET || '';
const MOMO_CURRENCY = process.env.MOMO_CURRENCY || 'EUR';
const MOMO_ENVIRONMENT = process.env.MOMO_ENVIRONMENT || 'sandbox';
const MOMO_CALLBACK_URL = process.env.MOMO_CALLBACK_URL || '';

// Token cache — reuse until 60s before expiry
let momoTokenCache = { token: '', expiresAt: 0 };

const getMomoToken = async () => {
  if (Date.now() < momoTokenCache.expiresAt) return momoTokenCache.token;

  // Basic auth = base64(userId:userSecret)
  const basicAuth = Buffer.from(`${MOMO_USER_ID}:${MOMO_USER_SECRET}`).toString('base64');

  const { data } = await axios.post(
    `${MOMO_BASE_URL}/collection/token/`,
    null, // empty body
    {
      headers: {
        Authorization: `Basic ${basicAuth}`,
        'Ocp-Apim-Subscription-Key': MOMO_SUBSCRIPTION_KEY,
        'Content-Length': '0',
      },
    }
  );

  // Cache token, expire 60s early to avoid edge cases
  momoTokenCache = {
    token: data.access_token,
    expiresAt: Date.now() + (data.expires_in - 60) * 1000,
  };

  return momoTokenCache.token;
};

const momoHeaders = (token, extraHeaders = {}) => ({
  Authorization: `Bearer ${token}`,
  'Ocp-Apim-Subscription-Key': MOMO_SUBSCRIPTION_KEY,
  'X-Target-Environment': MOMO_ENVIRONMENT,
  'Content-Type': 'application/json',
  ...extraHeaders,
});

// POST /collection/v1_0/requesttopay
// Returns 202 Accepted — no body. The referenceId we send IS the transaction ID.
export const initiateMomoPayment = async (req, res) => {
  try {
    const amount = parseAmount(req.body.amount);
    const { phoneNumber } = req.body;
    if (!amount) return res.status(400).json({ error: 'Amount must be a positive number' });
    if (!phoneNumber) return res.status(400).json({ error: 'Phone number is required' });

    const feePercentage = parseFloat(process.env.TRANSACTION_FEE_PERCENTAGE || 5);
    const feeAmount = parseFloat((amount * (feePercentage / 100)).toFixed(2));
    const totalCharged = parseFloat((amount + feeAmount).toFixed(2));

    // We generate the referenceId — MTN uses it as the transaction ID
    const referenceId = crypto.randomUUID();
    const token = await getMomoToken();

    // 202 Accepted means the request was received — poll getTransaction to confirm
    await axios.post(
      `${MOMO_BASE_URL}/collection/v1_0/requesttopay`,
      {
        amount: totalCharged.toString(),
        currency: MOMO_CURRENCY,
        externalId: referenceId,
        payer: {
          partyIdType: 'MSISDN',
          partyId: phoneNumber.replace(/\D/g, ''), // digits only
        },
        payerMessage: `Pmail wallet top-up $${amount}`,
        payeeNote: `Deposit $${amount} + $${feeAmount} fee`,
      },
      {
        headers: momoHeaders(token, {
          'X-Reference-Id': referenceId,
          ...(MOMO_CALLBACK_URL ? { 'X-Callback-Url': MOMO_CALLBACK_URL } : {}),
        }),
      }
    );

    // Store pending record so we can credit the right amount on confirmation
    await prisma.transaction.create({
      data: {
        userId: req.user.id,
        type: 'DEPOSIT_PENDING',
        amount: 0,
        description: `MoMo pending:${referenceId}:${amount}:${feeAmount}`,
      },
    });

    res.json({ referenceId, amount, feeAmount, totalCharged, feePercentage, status: 'PENDING' });
  } catch (err) {
    console.error('MoMo initiate error:', err?.response?.data || err.message);
    res.status(500).json({ error: 'Failed to initiate MoMo payment' });
  }
};

// GET /collection/v1_0/requesttopay/{referenceId}
// Status: PENDING | SUCCESSFUL | FAILED
export const checkMomoPayment = async (req, res) => {
  try {
    const { referenceId } = req.params;
    const userId = req.user.id;

    const token = await getMomoToken();
    const { data } = await axios.get(
      `${MOMO_BASE_URL}/collection/v1_0/requesttopay/${referenceId}`,
      { headers: momoHeaders(token) }
    );

    // Still waiting for payer to approve
    if (data.status === 'PENDING') return res.json({ status: 'PENDING' });

    // Payment failed on MTN side
    if (data.status === 'FAILED') {
      return res.json({ status: 'FAILED', reason: data.reason });
    }

    // SUCCESSFUL — credit wallet (idempotent)
    const alreadyCredited = await prisma.transaction.findFirst({
      where: { userId, description: { contains: `MoMo confirmed:${referenceId}` }, type: 'DEPOSIT' },
    });
    if (alreadyCredited) {
      const user = await prisma.user.findUnique({ where: { id: userId }, select: { walletBalance: true } });
      return res.json({ status: 'SUCCESSFUL', walletBalance: user.walletBalance, alreadyProcessed: true });
    }

    // Retrieve deposit amount from the pending record
    const pending = await prisma.transaction.findFirst({
      where: { userId, description: { contains: `MoMo pending:${referenceId}` } },
    });
    const parts = pending?.description?.split(':') || [];
    const depositAmount = parseFloat(parts[2]) || parseFloat(data.amount);
    const feeAmount = parseFloat(parts[3]) || 0;

    const [user] = await prisma.$transaction([
      prisma.user.update({
        where: { id: userId },
        data: { walletBalance: { increment: depositAmount } },
        select: { walletBalance: true },
      }),
      prisma.transaction.create({
        data: {
          userId,
          type: 'DEPOSIT',
          amount: depositAmount,
          description: `MoMo confirmed:${referenceId} deposit:$${depositAmount} fee:$${feeAmount} mtn:${data.financialTransactionId || ''}`,
        },
      }),
      prisma.platformEarning.create({
        data: { userId, feeAmount, depositAmount, source: 'MOMO', referenceId },
      }),
    ]);

    res.json({ status: 'SUCCESSFUL', walletBalance: user.walletBalance, depositAmount, feeAmount });
  } catch (err) {
    console.error('MoMo check error:', err?.response?.data || err.message);
    res.status(500).json({ error: 'Failed to check MoMo payment status' });
  }
};

// Webhook callback from MTN servers (X-Callback-Url)
// MTN POSTs the transaction result here when payment completes
export const momoWebhook = async (req, res) => {
  try {
    // MTN sends the full transaction object
    const { externalId, status, financialTransactionId, amount } = req.body;
    if (!externalId || status !== 'SUCCESSFUL') return res.sendStatus(200);

    const pending = await prisma.transaction.findFirst({
      where: { description: { contains: `MoMo pending:${externalId}` } },
    });
    if (!pending) return res.sendStatus(200);

    const alreadyCredited = await prisma.transaction.findFirst({
      where: { userId: pending.userId, description: { contains: `MoMo confirmed:${externalId}` }, type: 'DEPOSIT' },
    });
    if (alreadyCredited) return res.sendStatus(200);

    const parts = pending.description.split(':');
    const depositAmount = parseFloat(parts[2]) || parseFloat(amount) || 0;
    const feeAmount = parseFloat(parts[3]) || 0;

    await prisma.$transaction([
      prisma.user.update({
        where: { id: pending.userId },
        data: { walletBalance: { increment: depositAmount } },
      }),
      prisma.transaction.create({
        data: {
          userId: pending.userId,
          type: 'DEPOSIT',
          amount: depositAmount,
          description: `MoMo confirmed:${externalId} deposit:$${depositAmount} fee:$${feeAmount} mtn:${financialTransactionId || ''}`,
        },
      }),
      prisma.platformEarning.create({
        data: { userId: pending.userId, feeAmount, depositAmount, source: 'MOMO', referenceId: externalId },
      }),
    ]);

    res.sendStatus(200);
  } catch (err) {
    console.error('MoMo webhook error:', err.message);
    res.sendStatus(500);
  }
};


const POLAR_API_URL = process.env.POLAR_API_URL || 'http://localhost:8081';
const POLAR_MACAROON = process.env.POLAR_MACAROON || '';

// Fetch live BTC price with a 5-minute cache
let btcPriceCache = { price: 60000, fetchedAt: 0 };
const getBtcPrice = async () => {
  const now = Date.now();
  if (now - btcPriceCache.fetchedAt < 5 * 60 * 1000) return btcPriceCache.price;
  try {
    const r = await axios.get('https://api.coinbase.com/v2/prices/BTC-USD/spot', { timeout: 3000 });
    const price = parseFloat(r.data?.data?.amount);
    if (price > 0) { btcPriceCache = { price, fetchedAt: now }; return price; }
  } catch { /* use cached */ }
  return btcPriceCache.price;
};

const usdToSats = async (usd) => {
  const btcPrice = await getBtcPrice();
  return Math.floor((usd / btcPrice) * 1e8);
};
const satsToUsd = async (sats) => {
  const btcPrice = await getBtcPrice();
  return (sats / 1e8) * btcPrice;
};

const lnHeaders = () => ({ 'Grpc-Metadata-macaroon': POLAR_MACAROON });

const createLNInvoice = async (amountSats, description) => {
  const r = await axios.post(`${POLAR_API_URL}/v1/invoices`,
    { value: amountSats.toString(), memo: description, expiry: '3600' },
    { headers: lnHeaders() });
  return r.data;
};

const checkLNInvoice = async (paymentHash) => {
  // paymentHash may arrive as base64 — encode for URL
  const encoded = encodeURIComponent(paymentHash);
  const r = await axios.get(`${POLAR_API_URL}/v1/invoice/${encoded}`, { headers: lnHeaders() });
  return r.data;
};

const sendLNPayment = async (paymentRequest) => {
  const r = await axios.post(`${POLAR_API_URL}/v1/channels/transactions`,
    { payment_request: paymentRequest },
    { headers: lnHeaders() });
  return r.data;
};

